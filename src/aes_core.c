/* Round constants used during key expansion (Rcon[i] = x^(i-1) mod irreducible poly). */
static const uint8_t rcon[11] = {
 0x00, /* unused */
 0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36
};

/* ─────────────────────────────────────────────────────────── *
 * GF(2^8) multiplication helpers (used by MixColumns).       *
 * ─────────────────────────────────────────────────────────── */
static inline uint8_t xtime(uint8_t x) {
    /* Multiply by 2 in GF(2^8) with irreducible polynomial 0x11b. */
    return (uint8_t)((x << 1) ^ ((x >> 7) & 1 ? 0x1b : 0x00));
}
static inline uint8_t gmul(uint8_t a, uint8_t b) {
    /* Multiply two bytes in GF(2^8), using xtime + bit-scan. */
    uint8_t r = 0;
    uint8_t t = a;
    for (int i = 0; i < 8; i++) {
        if (b & 1) r ^= t;
        t = xtime(t);
        b >>= 1;
    }
    return r;
}

/* ─────────────────────────────────────────────────────────── *
 * Key Expansion                                               *
 * ─────────────────────────────────────────────────────────── */

/* RotWord: cyclic rotate word [a0 a1 a2 a3] -> [a1 a2 a3 a0]. */
static inline uint32_t rotword(uint32_t w) {
    return ((w << 8) | (w >> 24)) & 0xFFFFFFFFu;
}
/* SubWord: apply S-box to each byte of the word. */
static inline uint32_t subword(uint32_t w) {
    return ((uint32_t)sbox[(w >> 24) & 0xFF] << 24) |
           ((uint32_t)sbox[(w >> 16) & 0xFF] << 16) |
           ((uint32_t)sbox[(w >>  8) & 0xFF] <<  8) |
           ((uint32_t)sbox[(w      ) & 0xFF]);
}

aes_err_t aes_init(aes_ctx_t* ctx, const uint8_t* key, size_t key_len) {
    if (!ctx || !key) return AES_ERR_INVALID_ARG;

    uint8_t Nk; /* Number of 32-bit words in the key. */
    uint8_t Nr; /* Number of rounds. */
    switch (key_len) {
        case AES128_KEY_SIZE: Nk = 4; Nr = AES128_ROUNDS; break;
        case AES192_KEY_SIZE: Nk = 6; Nr = AES192_ROUNDS; break;
        case AES256_KEY_SIZE: Nk = 8; Nr = AES256_ROUNDS; break;
        default: return AES_ERR_INVALID_KEY_SIZE;
    }

    ctx->rounds = Nr;
    uint8_t total = (Nr + 1) * 4; /* total words in round keys */
    if (total > AES_MAX_RK_WORDS) return AES_ERR_BUFFER_OVERRUN;

    /* Copy original key bytes as big-endian words. */
    for (uint8_t i = 0; i < Nk; i++) {
        ctx->rk[i] = ((uint32_t)key[i*4+0] << 24) |
                     ((uint32_t)key[i*4+1] << 16) |
                     ((uint32_t)key[i*4+2] <<  8) |
                     ((uint32_t)key[i*4+3]);
    }

    /* Extend remaining words. */
    for (uint8_t i = Nk; i < total; i++) {
        uint32_t t = ctx->rk[i - 1];
        if ((i % Nk) == 0) {
            t = subword(rotword(t)) ^ ((uint32_t)rcon[i / Nk] << 24);
        } else if (Nk > 6 && (i % Nk) == 4) {
            t = subword(t);
        }
        ctx->rk[i] = ctx->rk[i - Nk] ^ t;
    }

    return AES_OK;
}

/* ─────────────────────────────────────────────────────────── *
 * Round transformations                                       *
 * State layout: 4x4 column-major matrix of bytes.            *
 *   state[0] state[4] state[ 8] state[12]  <- row 0          *
 *   state[1] state[5] state[ 9] state[13]  <- row 1          *
 *   state[2] state[6] state[10] state[14]  <- row 2          *
 *   state[3] state[7] state[11] state[15]  <- row 3          *
 * ─────────────────────────────────────────────────────────── */

static void sub_bytes(uint8_t s[16]) {
    for (int i = 0; i < 16; i++) s[i] = sbox[s[i]];
}
static void inv_sub_bytes(uint8_t s[16]) {
    for (int i = 0; i < 16; i++) s[i] = inv_sbox[s[i]];
}

static void shift_rows(uint8_t s[16]) {
    uint8_t t;
    /* Row 1: shift left by 1 */
    t      = s[1];
    s[1]   = s[5];  s[5]   = s[9];   s[9]   = s[13];  s[13]  = t;
    /* Row 2: shift left by 2 */
    t = s[2];  s[2] = s[10]; s[10] = t;
    t = s[6];  s[6] = s[14]; s[14] = t;
    /* Row 3: shift left by 3 (== right by 1) */
    t      = s[15];
    s[15]  = s[11]; s[11]  = s[7];   s[7]   = s[3];   s[3]   = t;
}
static void inv_shift_rows(uint8_t s[16]) {
    uint8_t t;
    /* Row 1: shift right by 1 */
    t      = s[13];
    s[13]  = s[9];  s[9]   = s[5];   s[5]   = s[1];   s[1]   = t;
    /* Row 2: shift right by 2 */
    t = s[2];  s[2] = s[10]; s[10] = t;
    t = s[6];  s[6] = s[14]; s[14] = t;
    /* Row 3: shift right by 3 (== left by 1) */
    t      = s[3];
    s[3]   = s[7];  s[7]   = s[11];  s[11]  = s[15];  s[15]  = t;
}

static void mix_columns(uint8_t s[16]) {
    for (int c = 0; c < 4; c++) {
        uint8_t a0 = s[c*4+0], a1 = s[c*4+1], a2 = s[c*4+2], a3 = s[c*4+3];
        uint8_t t  = a0 ^ a1 ^ a2 ^ a3;
        uint8_t u  = a0;
        s[c*4+0] ^= t ^ xtime(a0 ^ a1);
        s[c*4+1] ^= t ^ xtime(a1 ^ a2);
        s[c*4+2] ^= t ^ xtime(a2 ^ a3);
        s[c*4+3] ^= t ^ xtime(a3 ^ u);
    }
}
static void inv_mix_columns(uint8_t s[16]) {
    /* Each column multiplied by [0e 0b 0d 09]^T in GF(2^8). */
    for (int c = 0; c < 4; c++) {
        uint8_t a0 = s[c*4+0], a1 = s[c*4+1], a2 = s[c*4+2], a3 = s[c*4+3];
        s[c*4+0] = gmul(a0,0x0e) ^ gmul(a1,0x0b) ^ gmul(a2,0x0d) ^ gmul(a3,0x09);
        s[c*4+1] = gmul(a0,0x09) ^ gmul(a1,0x0e) ^ gmul(a2,0x0b) ^ gmul(a3,0x0d);
        s[c*4+2] = gmul(a0,0x0d) ^ gmul(a1,0x09) ^ gmul(a2,0x0e) ^ gmul(a3,0x0b);
        s[c*4+3] = gmul(a0,0x0b) ^ gmul(a1,0x0d) ^ gmul(a2,0x09) ^ gmul(a3,0x0e);
    }
}

static void add_round_key(uint8_t s[16], const uint32_t* rk) {
    for (int i = 0; i < 4; i++) {
        uint32_t w = rk[i];
        s[i*4+0] ^= (uint8_t)((w >> 24) & 0xFF);
        s[i*4+1] ^= (uint8_t)((w >> 16) & 0xFF);
        s[i*4+2] ^= (uint8_t)((w >>  8) & 0xFF);
        s[i*4+3] ^= (uint8_t)((w      ) & 0xFF);
    }
}

/* ─────────────────────────────────────────────────────────── *
 * Public encrypt / decrypt (single 16-byte block).           *
 * ─────────────────────────────────────────────────────────── */

void aes_encrypt_block(const aes_ctx_t* ctx, const uint8_t* in, uint8_t* out) {
    uint8_t s[16];
    memcpy(s, in, 16);

    add_round_key(s, &ctx->rk[0]);

    /* Main rounds */
    for (uint8_t r = 1; r < ctx->rounds; r++) {
        sub_bytes(s);
        shift_rows(s);
        mix_columns(s);
        add_round_key(s, &ctx->rk[r*4]);
    }

    /* Final round (no MixColumns) */
    sub_bytes(s);
    shift_rows(s);
    add_round_key(s, &ctx->rk[ctx->rounds * 4]);

    memcpy(out, s, 16);
}

void aes_decrypt_block(const aes_ctx_t* ctx, const uint8_t* in, uint8_t* out) {
    uint8_t s[16];
    memcpy(s, in, 16);

    add_round_key(s, &ctx->rk[ctx->rounds * 4]);

    /* Inverse main rounds */
    for (uint8_t r = ctx->rounds - 1; r >= 1; r--) {
        inv_shift_rows(s);
        inv_sub_bytes(s);
        add_round_key(s, &ctx->rk[r*4]);
        inv_mix_columns(s);
    }

    /* Initial (final-in-reverse) round: no InvMixColumns */
    inv_shift_rows(s);
    inv_sub_bytes(s);
    add_round_key(s, &ctx->rk[0]);

    memcpy(out, s, 16);
}

void aes_zeroize_ctx(aes_ctx_t* ctx) {
    if (!ctx) return;
    /* Best-effort; compiler may optimize away memset, so we use volatile trick. */
    volatile uint8_t* p = (volatile uint8_t*)ctx;
    for (size_t i = 0; i < sizeof(*ctx); i++) p[i] = 0;
}
